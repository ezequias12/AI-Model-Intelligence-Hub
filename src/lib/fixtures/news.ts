export function buildFixtureNews(now: Date): NewsItem[] {
  return NEWS_SEEDS.map((seed) => {
    const canonicalUrl = canonicalizeUrl(seed.url);
    const publishedAt =
      seed.hoursAgo === null
        ? null
        : new Date(now.getTime() - seed.hoursAgo * 3_600_000).toISOString();

    return {
      id: seed.id,
      domain: seed.domain,
      category: seed.category,
      title: seed.title,
      url: seed.url,
      canonicalUrl,
      sourceId: seed.sourceId,
      sourceName: seed.sourceName,
      trustTier: seed.trustTier,
      publishedAt,
      discoveredAt: now.toISOString(),
      excerpt: seed.excerpt,
      summary: null,
      entities: seed.entities,
      providerIds: seed.providerSlugs.map((slug) => `provider:${slug}`),
      official: seed.official,
      corroborated: seed.corroborated,
      developing: seed.developing ?? false,
      contentHash: newsContentHash({ canonicalUrl, title: seed.title, publishedAt }),
      clusterId: null,
    } satisfies NewsItem;
  });
}
